// เนื้อหาหน้า "วิธีเล่น" และปุ่ม "?" ของแต่ละช่วง (Q10) — แก้ข้อความได้ที่ไฟล์นี้ไฟล์เดียว
// ตัวเลขทั้งหมดดึงจาก config.js ผ่าน c (เช่น c.voteSeconds) ห้ามเขียนตัวเลขตายตัว
(function (root) {
  'use strict';
  const sec = (s) => (s >= 60 && s % 60 === 0 ? `${s / 60} นาที` : `${s} วินาที`);
  const total = (c) => c.deckCount3 + c.deckCount4 + c.deckCount5;
  // รวมจำนวนผู้เล่นที่ใช้แต้มเท่ากันเป็นช่วง เช่น "3–5 คน: 15 แต้ม"
  function winList(c) {
    const t = c.winPointsByPlayers || {}, rows = [];
    for (let n = c.minPlayers; n <= c.maxPlayers; n++) {
      const last = rows[rows.length - 1];
      if (last && last.v === t[n]) last.to = n; else rows.push({ from: n, to: n, v: t[n] });
    }
    return '<ul>' + rows.map((r) => `<li>${r.from === r.to ? r.from : r.from + '–' + r.to} คน: <b>${r.v} แต้ม</b></li>`).join('') + '</ul>';
  }

  function page(c) {
    return `
<h2>เป้าหมาย</h2>
<p>เก็บทองให้ถึงเกณฑ์ก่อนคนอื่น เกณฑ์ขึ้นกับจำนวนคนในห้อง:</p>
${winList(c)}
<p>ทองมี ${total(c)} แท่ง ค่า 3 แต้ม ${c.deckCount3} แท่ง, ค่า 4 แต้ม ${c.deckCount4} แท่ง, ค่า 5 แต้ม ${c.deckCount5} แท่ง
${c.hiddenScores ? 'คนอื่นเห็นแค่ว่าคุณมีทองกี่แท่ง แต่ไม่รู้ว่าแต่ละแท่งค่าเท่าไหร่' : 'ทุกคนเห็นแต้มของกันและกัน'}</p>

<h2>หนึ่งรอบเล่นอย่างไร</h2>
<p>ต้นรอบจะวางทอง <b>${c.potSize} แท่ง</b> ไว้กลางวง ทุกคนแย่งกันเป็น <b>ผู้รอดชีวิต 2 คนสุดท้าย</b> เพื่อไปดวลแบ่งทองกองนี้</p>
<ol>
<li><b>เจรจา</b> ${sec(c.conspireSecondsFirst)}${c.conspireSecondsNext !== c.conspireSecondsFirst ? ` (โหวตซ้ำในรอบเดียวกันเหลือ ${sec(c.conspireSecondsNext)})` : ''} — คุยในแชทกลาง ตกลงกันว่าจะโหวตใคร (จะโกหกก็ได้)</li>
<li><b>โหวต</b> ${sec(c.voteSeconds)} — ทุกคนที่ยังรอดเลือกไพ่ 1 ใบแบบลับ: การ์ดหน่วยรบของคนที่อยากกำจัด หรือไพ่ <b>DEFENSE</b> แล้วกด <b>ยืนยัน</b></li>
<li><b>เปิดผล</b> — คนที่ได้โหวตมากที่สุดคือ <b>เป้าหมาย</b> และตกรอบ (ถ้าเสมอกัน ตกทุกคน)</li>
<li>ถ้ายังรอดมากกว่า 2 คน เจรจาและโหวตใหม่ในกลุ่มที่เหลือ จนเหลือไม่เกิน 2 คน</li>
</ol>

<h2>กฎสำคัญตอนเปิดผลโหวต</h2>
<ul>
<li><b>ต้องโหวตถูกคน</b> — ถ้าคุณโหวตคนที่ไม่ได้เป็นเป้าหมาย คุณก็ตกรอบด้วย</li>
<li><b>ไม่โหวต = ตกรอบ</b> — ถ้าหมดเวลาแล้วยังไม่เลือกอะไรเลย คุณตกรอบ </li>
<li><b>เลือกแล้วไม่ต้องกลัวลืมกด</b> — ถ้าเลือกไว้แล้วแต่ยังไม่กดยืนยัน พอหมดเวลา ระบบใช้ใบที่เลือกไว้เป็นคำตอบสุดท้าย (ใช้กับการเลือกทุกแบบในเกม)</li>
<li>โหวตตัวเองไม่ได้</li>
</ul>
<div class="ex"><b>ตัวอย่าง</b> 6 คน: A, B, C, D โหวต E ส่วน E กับ F โหวต A<br>
→ E ได้ 4 โหวต เป็นเป้าหมาย ตกรอบ<br>
→ F โหวต A ซึ่งไม่ใช่เป้าหมาย F ตกรอบด้วย<br>
→ เหลือ A, B, C, D ไปโหวตต่อ</div>

<h2>ไพ่ DEFENSE</h2>
<ul>
<li>ใช้แทนการโหวต เป็นการตั้งรับ ถ้าคุณ <b>เป็นเป้าหมาย</b> คุณรอด และเลือกกำจัดคนที่โหวตคุณได้ 1 คน (เลือกได้ภายใน ${sec(c.defensePickSeconds)})</li>
<li>ถ้าคุณ <b>ไม่ได้เป็นเป้าหมาย</b> ไพ่นี้ไม่มีผล และคุณตกรอบเอง</li>
<li>${c.defenseTimeoutPick === 'random' ? 'ถ้าหมดเวลาแล้วยังไม่เลือก ระบบสุ่มให้ 1 คน' : 'ถ้าหมดเวลาแล้วยังไม่เลือก จะไม่มีใครโดนกำจัดเพิ่ม'}</li>
</ul>
<div class="ex"><b>ตัวอย่าง</b> A ใช้ DEFENSE ส่วน B, C, D โหวต A และ E โหวต B<br>
→ A ได้ 3 โหวต เป็นเป้าหมาย แต่ตั้งรับไว้ จึงรอด แล้วสวนกลับเลือกกำจัด C<br>
→ E โหวต B ซึ่งไม่ใช่เป้าหมาย E ตกรอบ<br>
→ เหลือ A, B, D</div>

<h2>จบรอบ</h2>
<ul>
<li><b>เหลือ 2 คน</b> → ไปดวลสุดท้าย (ดูด้านล่าง)</li>
<li><b>เหลือ 1 คน</b> (เกิดได้เพราะ DEFENSE เท่านั้น) → ได้ทองกลางวงไปทั้งหมด</li>
<li><b>ไม่เหลือใครเลย</b> → ทองกลางวงค้างไว้รอบหน้า${c.zeroSurvivorCompensation ? ` และคนที่ตกรอบก่อนการโหวตครั้งสุดท้ายของรอบนั้นได้ทองปลอบใจคนละ ${c.compensationBars} แท่งจากกองทอง` : ''}</li>
</ul>

<h2>ดวลสุดท้าย</h2>
<p>2 คนสุดท้ายคุยกัน ${sec(c.showdownTalkSeconds)} แล้วเลือกไพ่ลับคนละ 1 ใบภายใน ${sec(c.showdownPickSeconds)}: <b>SHARE</b>, <b>STEAL</b> หรือ <b>GRAB ONE &amp; GO</b> แล้วเปิดพร้อมกัน (สมมติกลางวงมี ${c.potSize} แท่ง)</p>
<table class="sd">
<tr><th>คุณ \\ อีกฝ่าย</th><th>SHARE</th><th>STEAL</th><th>GRAB</th></tr>
<tr><th>SHARE</th><td>2 / 2</td><td>0 / 4</td><td>3 / 1</td></tr>
<tr><th>STEAL</th><td>4 / 0</td><td>0 / 0 *</td><td>3 / 1</td></tr>
<tr><th>GRAB</th><td>1 / 3</td><td>1 / 3</td><td>1 / 1 **</td></tr>
</table>
<p class="small">ตัวเลข = แท่งที่คุณได้ / แท่งที่อีกฝ่ายได้ ได้แท่งไหนเป็นการสุ่ม<br>
* STEAL ชน STEAL: ไม่มีใครได้ ทองค้างไว้รอบหน้า และทุกคนที่ไม่ได้ดวลได้ทองปลอบใจคนละ ${c.compensationBars} แท่ง<br>
** GRAB ชน GRAB: คนละ 1 แท่ง อีก 2 แท่งค้างไว้รอบหน้า<br>
ถ้าหมดเวลาแล้วยังไม่เลือก ระบบเลือก ${c.showdownTimeoutChoice.toUpperCase()} ให้</p>

<h2>ชนะเกม</h2>
<ul>
<li>ตรวจตอนจบทุกรอบ ใครถึงเกณฑ์แต้มก่อนชนะ ถ้าถึงพร้อมกันหลายคน คนแต้มสูงกว่าชนะ</li>
<li>แต้มสูงสุดเท่ากัน 2 คน → ดวลตัดสิน (สูงสุด ${c.tiebreakMaxShowdowns} ครั้ง ไม่มีทองปลอบใจ) ถ้ายังเท่ากันอยู่ ชนะร่วม</li>
<li>แต้มสูงสุดเท่ากัน 3 คนขึ้นไป → ชนะร่วม</li>
<li>ถ้าทองในกองหมดก่อน เกมจบทันทีหลังรอบนั้น คนแต้มสูงสุดชนะ</li>
</ul>

<h2>อื่น ๆ</h2>
<ul>
<li>เล่นได้ ${c.minPlayers}–${c.maxPlayers} คน คนตกรอบยังพิมพ์แชทได้</li>
<li>หลุดหรือรีเฟรช เปิดลิงก์เดิมแล้วกลับเข้าที่นั่งเดิมได้เลย ถ้าเปลี่ยนเครื่อง ให้เข้าห้องด้วยชื่อเดิมแล้วรอ GM อนุมัติ</li>
<li>GM (คนสร้างห้อง) หยุดเกม เล่นต่อ หรือกดข้ามได้ทุกช่วงโดยไม่ต้องรอเวลาหมด (ผลเหมือนเวลาหมด) ทุกคนจะเห็นว่า GM ทำอะไร</li>
</ul>`;
  }

  const HELP = {
    LOBBY: (c) => `รอเพื่อนเข้าห้องให้ครบ ${c.minPlayers}–${c.maxPlayers} คน<br>แตะการ์ดสีเพื่อเลือกหน่วยรบของคุณ<br>GM กด <b>เริ่มเกม</b> เมื่อพร้อม`,
    CONSPIRE: (c) => `คุยในแชทกลาง ตกลงว่าจะโหวตใคร (โกหกได้)<br>มีเวลา ${sec(c.conspireSecondsFirst)} (โหวตซ้ำ ${sec(c.conspireSecondsNext)}) แล้วจะเข้าช่วงโหวต<br>จำไว้: โหวตผิดคนก็ตกรอบ`,
    VOTE: (c) => `แตะการ์ดเพื่อดู แล้วกด <b>เลือกใบนี้</b> จากนั้นกด <b>ยืนยัน</b> (ถ้าไม่ทันกด ระบบใช้ใบที่เลือกไว้)<br>ได้โหวตมากสุด = ตกรอบ, โหวตคนที่ไม่ได้เป็นเป้าหมาย = ตกรอบ<br>ไม่เลือกอะไรเลยก่อนหมดเวลา = ตกรอบ<br>DEFENSE: ถ้าคุณเป็นเป้าหมาย คุณรอดและสวนกลับกำจัดคนที่โหวตคุณได้ 1 คน`,
    AMBUSH_PICK: (c) => `คนที่ใช้ DEFENSE สำเร็จ เลือกกำจัดคนที่โหวตตัวเอง 1 คน<br>มีเวลา ${sec(c.defensePickSeconds)}`,
    RESULT: () => `ดูว่าใครโหวตใคร และใครตกรอบเพราะอะไร<br>เหลือ 3 คนขึ้นไป = โหวตต่อ, เหลือ 2 คน = ดวลสุดท้าย`,
    ROUND_END: (c) => `เหลือ 1 คน = ได้ทองกลางวงทั้งหมด<br>ไม่เหลือใคร = ทองค้างรอบหน้า${c.zeroSurvivorCompensation ? ' และคนที่ตกรอบก่อนได้ทองปลอบใจ' : ''}`,
    SHOWDOWN_TALK: (c) => `2 คนสุดท้ายคุยกันก่อนเลือกไพ่ ${sec(c.showdownTalkSeconds)}<br>SHARE ชน SHARE = คนละ 2 แท่ง, STEAL ชน SHARE = STEAL ได้หมด<br>STEAL ชน STEAL = ไม่มีใครได้ คนอื่นได้ทองปลอบใจ`,
    SHOWDOWN_PICK: (c) => `เลือกไพ่ลับ 1 ใบ แล้วกดยืนยัน (${sec(c.showdownPickSeconds)})<br>SHARE แบ่งกัน, STEAL แย่งทั้งหมด, GRAB ONE &amp; GO หยิบ 1 แท่งแล้วหนี<br>หมดเวลา = ระบบเลือก ${c.showdownTimeoutChoice.toUpperCase()} ให้`,
    SHOWDOWN_RESULT: () => `ดูผลการดวล ทองที่ได้สุ่มจากกองกลาง<br>จบรอบนี้แล้วตรวจว่ามีใครถึงเกณฑ์ชนะหรือยัง`,
    GAME_END: () => `เกมจบแล้ว ดูแต้มของทุกคนได้<br>GM กด <b>เล่นอีกครั้ง</b> เพื่อเริ่มใหม่ด้วยผู้เล่นชุดเดิม`,
  };

  root.RULES = { page, help: (phase, c) => (HELP[phase] ? HELP[phase](c) : '') };
})(window);
